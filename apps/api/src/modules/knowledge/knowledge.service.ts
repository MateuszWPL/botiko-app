import {
  Injectable,
  NotFoundException,
  Logger,
} from '@nestjs/common';
import { randomUUID } from 'crypto';
import { Prisma } from '@prisma/client';
import { PrismaService } from '../../prisma/prisma.service';
import type { AddChunkDto } from './dto/add-chunk.dto';

export interface KnowledgeChunkResponse {
  id: string;
  content: string;
  category: string | null;
  createdAt: Date;
}

@Injectable()
export class KnowledgeService {
  private readonly logger = new Logger(KnowledgeService.name);

  constructor(private readonly prisma: PrismaService) {}

  async addChunk(
    tenantId: string,
    botId: string,
    dto: AddChunkDto,
  ): Promise<{ id: string }> {
    const bot = await this.prisma.bot.findFirst({
      where: { id: botId, tenantId },
      select: { id: true },
    });

    if (!bot) {
      throw new NotFoundException('Bot not found');
    }

    const id = randomUUID();

    // Zero-vector placeholder — real embedding generated by EmbeddingService (Sprint 3)
    await this.prisma.$executeRaw`
      INSERT INTO "KnowledgeChunk" (id, "botId", content, embedding, category, "createdAt")
      VALUES (
        ${id},
        ${botId},
        ${dto.content},
        ${Prisma.raw(`array_fill(0::float4, ARRAY[1536])::vector(1536)`)},
        ${dto.category ?? null},
        NOW()
      )
    `;

    this.logger.log(`Knowledge chunk added: ${id} to bot: ${botId}`);
    return { id };
  }

  async listChunks(
    tenantId: string,
    botId: string,
  ): Promise<KnowledgeChunkResponse[]> {
    const bot = await this.prisma.bot.findFirst({
      where: { id: botId, tenantId },
      select: { id: true },
    });

    if (!bot) {
      throw new NotFoundException('Bot not found');
    }

    return this.prisma.knowledgeChunk.findMany({
      where: { botId },
      select: {
        id: true,
        content: true,
        category: true,
        createdAt: true,
      },
      orderBy: { createdAt: 'desc' },
    });
  }

  async deleteChunk(tenantId: string, chunkId: string): Promise<void> {
    const chunk = await this.prisma.knowledgeChunk.findFirst({
      where: {
        id: chunkId,
        bot: { tenantId },
      },
      select: { id: true },
    });

    if (!chunk) {
      throw new NotFoundException('Knowledge chunk not found');
    }

    await this.prisma.knowledgeChunk.delete({ where: { id: chunkId } });
    this.logger.log(`Knowledge chunk deleted: ${chunkId}`);
  }
}
